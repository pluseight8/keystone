export class BrowserContextExtractor {
  constructor(private readonly defaults: BrowserContextOptions = {}) {}

  extract(page: BrowserPageState, options: BrowserContextOptions = {}): BrowserContext {
    const maxText = boundedInt(options.maxTextBytes ?? this.defaults.maxTextBytes, 256, 64 * 1024, 16 * 1024);
    const maxElements = boundedInt(options.maxElements ?? this.defaults.maxElements, 1, 256, 64);
    const maxA11y = boundedInt(options.maxAccessibilityBytes ?? this.defaults.maxAccessibilityBytes, 0, 64 * 1024, 8 * 1024);
    const visibleText = page.visibleText.slice(0, maxText);
    const accessibilitySnapshot = page.accessibilitySnapshot?.slice(0, maxA11y);
    return {
      version: 1,
      sessionId: '',
      tabId: page.tabId,
      url: page.url,
      origin: page.origin,
      title: page.title.slice(0, 512),
      pageRevision: page.pageRevision,
      dataClass: page.dataClass,
      visibleText,
      interactiveElements: page.interactiveElements.slice(0, maxElements).map(sanitizeElement).filter(element => element.id.length > 0),
      ...(accessibilitySnapshot ? { accessibilitySnapshot } : {}),
      ...(options.includeScreenshot && page.screenshotRef ? { screenshotRef: page.screenshotRef } : {}),
      untrusted: true,
      omittedTextBytes: Math.max(0, page.visibleText.length - visibleText.length),
    };
  }

  extractForSession(sessionId: string, page: BrowserPageState, options: BrowserContextOptions = {}): BrowserContext {
    return { ...this.extract(page, options), sessionId };
  }
}

