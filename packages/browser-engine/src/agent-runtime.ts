/**
 * Typed browser-agent boundary.
 *
 * This module deliberately knows nothing about a DOM, JavaScript evaluation,
 * cookies, or a particular browser vendor.  A host adapter supplies a small
 * observation/action surface and the runtime enforces scope, revisions,
 * budgets, privacy, and confirmation before the adapter is called.
 */

