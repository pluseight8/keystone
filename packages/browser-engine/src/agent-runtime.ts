const DEFAULT_SCOPE: Required<Pick<BrowserPermissionScope, 'maxTabs' | 'maxNavigations' | 'maxSteps' | 'maxRuntimeMs' | 'maxFailedActions' | 'maxDownloads' | 'maxDownloadBytes' | 'allowPrivatePages' | 'allowDownloads' | 'allowUploads'>> = {
  maxTabs: 5,
  maxNavigations: 24,
  maxSteps: 64,
  maxRuntimeMs: 120_000,
  maxFailedActions: 8,
  maxDownloads: 4,
  maxDownloadBytes: 50 * 1024 * 1024,
  allowPrivatePages: true,
  allowDownloads: true,
  allowUploads: true,
};

export class BrowserPolicy {
  constructor(private readonly baseScope: BrowserPermissionScope = {}) {}

  scopeFor(input?: BrowserPermissionScope): BrowserPermissionScope {
    return { ...DEFAULT_SCOPE, ...this.baseScope, ...(input ?? {}) };
  }

  authorize(session: BrowserSession, page: BrowserPageState | undefined, intent: BrowserIntent): BrowserPolicyDecision {
    const scope = this.scopeFor(session.scope);
    if (scope.allowedIntents && !scope.allowedIntents.includes(intent.type)) return denied('INTENT_NOT_ALLOWED', `Intent ${intent.type} is outside the browser scope.`);
    if (page && isPrivate(page.dataClass) && session.execution === 'external') return denied('PRIVATE_PAGE_EXTERNAL', 'External AI cannot access a private authenticated page.');
    if (page && isPrivate(page.dataClass) && scope.allowPrivatePages === false) return denied('INTENT_NOT_ALLOWED', 'Private page access is not granted.');
    if (intent.type === 'DOWNLOAD' && scope.allowDownloads === false) return denied('INTENT_NOT_ALLOWED', 'Downloads are not granted.');
    if (intent.type === 'UPLOAD_EXPLICIT_FILE' && scope.allowUploads === false) return denied('INTENT_NOT_ALLOWED', 'Uploads are not granted.');
    if (intent.type === 'UPLOAD_EXPLICIT_FILE' && (!intent.file || intent.file.explicitAuthorization !== true)) return denied('UPLOAD_NOT_EXPLICIT', 'Only an explicitly selected FileObject may be uploaded.');
    if (intent.type === 'UPLOAD_EXPLICIT_FILE' && intent.file?.dataClass === 'PRIVATE' && session.execution === 'external') return denied('PRIVATE_FILE_ACCESS_DENIED', 'External AI cannot upload a private FileObject.');
    if (intent.type === 'TYPE' && ((intent.target ?? intent.element ?? intent.elementRef) as BrowserInteractiveElement | undefined)?.inputType === 'password') return denied('CREDENTIAL_ACCESS_DENIED', 'Browser hosts perform password autofill; models cannot type credentials.');
    if (scope.requireConfirmationFor?.includes(intent.type) && intent.confirmed !== true) return { allowed: false, code: 'CONFIRMATION_REQUIRED', reason: 'User confirmation is required for this browser action.', requiresConfirmation: true };
    if ((intent.text ?? intent.value ?? intent.query)?.length && (intent.text ?? intent.value ?? intent.query)!.length > 16 * 1024) return denied('INVALID_ARGUMENT', 'Browser input/query exceeds the bounded context limit.');
    if (intent.timeoutMs !== undefined && (!Number.isSafeInteger(intent.timeoutMs) || intent.timeoutMs < 0 || intent.timeoutMs > 60_000)) return denied('INVALID_ARGUMENT', 'Browser wait timeout is outside the bounded limit.');
    if (intent.type === 'NAVIGATE' || intent.type === 'OPEN_TAB') {
      if (!intent.url) return denied('INVALID_ARGUMENT', 'A URL is required.');
      const origin = safeOrigin(intent.url);
      if (!origin) return denied('INVALID_REDIRECT', 'Only HTTP(S) navigation is allowed.');
      if (scope.allowedOrigins?.length && !scope.allowedOrigins.some(allowed => originMatches(origin, allowed))) return denied('ORIGIN_BLOCKED', `Origin ${origin} is outside the browser scope.`);
    }
    return { allowed: true };
  }
}

