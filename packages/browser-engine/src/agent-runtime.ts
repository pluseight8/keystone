export class BrowserAgentRuntime {
  private readonly sessions = new Map<string, MutableSession>();
  private readonly artifacts = new Map<string, BrowserArtifact>();
  private readonly host: BrowserHostAdapter;
  private readonly policy: BrowserPolicy;
  private readonly extractor: BrowserContextExtractor;
  private readonly now: () => number;
  private readonly budgets: BrowserRuntimeBudgets;
  private readonly toolPolicy?: BrowserToolPolicyBoundary;
  private readonly egressFirewall?: BrowserEgressFirewallBoundary;
  private readonly downloadBoundary?: BrowserDownloadBoundary;
  private readonly credentialAdapter?: BrowserCredentialAdapter;

  constructor(options: BrowserAgentRuntimeOptions) {
    const host = options?.host ?? options?.hostAdapter;
    if (!host || typeof host.observe !== 'function' || typeof host.execute !== 'function') throw new BrowserAgentError('INVALID_ARGUMENT', 'A typed browser host adapter is required.');
    this.host = host;
    this.policy = options.policy ?? new BrowserPolicy();
    this.extractor = options.extractor ?? new BrowserContextExtractor();
    this.now = options.now ?? (() => Date.now());
    this.budgets = normalizeBudgets(options.budgets);
    this.toolPolicy = options.toolPolicy;
    this.egressFirewall = options.egressFirewall;
    this.downloadBoundary = options.downloadBoundary;
    this.credentialAdapter = options.credentialAdapter;
  }

  createSession(input: BrowserSessionInput): BrowserSession {
    if (!safeId(input?.ownerAgentId, 256)) throw new BrowserAgentError('INVALID_ARGUMENT', 'ownerAgentId is required.');
    const idValue = input.id ?? randomId('browser-session');
    if (!safeId(idValue, 256) || this.sessions.has(idValue)) throw new BrowserAgentError('INVALID_ARGUMENT', 'Invalid or duplicate browser session id.');
    const scope = this.policy.scopeFor(input.scope ?? input.permissionScope);
    const session: MutableSession = {
      version: 1,
      id: idValue,
      ownerAgentId: input.ownerAgentId,
      execution: input.execution ?? 'local',
      scope,
      tabs: new Map(),
      activity: 'IDLE',
      paused: false,
      createdAt: iso(this.now),
      updatedAt: iso(this.now),
      counters: { steps: 0, navigations: 0, failedActions: 0, downloads: 0, downloadedBytes: 0 },
    };
    this.sessions.set(idValue, session);
    // Session creation is synchronous so callers can persist the session
    // before opening a host tab.  Hosts may call openTab immediately after
    // createSession when an initialUrl was requested.
    return this.snapshot(session);
  }

  getSession(sessionId: string): BrowserSession | undefined {
    const session = this.sessions.get(sessionId);
    return session ? this.snapshot(session) : undefined;
  }

  listSessions(): readonly BrowserSession[] { return [...this.sessions.values()].map(session => this.snapshot(session)); }

  async closeSession(sessionId: string): Promise<void> {
    const session = this.requireSession(sessionId);
    for (const tabId of session.tabs.keys()) if (this.host.closeTab) await this.host.closeTab(tabId, { sessionId });
    this.sessions.delete(sessionId);
  }

  async openTab(sessionId: string, url: string, title = 'Browser'): Promise<BrowserTabState> {
    const session = this.requireSession(sessionId);
    const normalized = safeHttpUrl(url);
    if (!normalized) throw new BrowserAgentError('INVALID_REDIRECT', 'Only HTTP(S) URLs are allowed.');
    const maxTabs = this.limit(session.scope.maxTabs, this.budgets.maxTabs);
    if (session.tabs.size >= maxTabs) throw new BrowserAgentError('TAB_LIMIT', 'Browser tab budget exceeded.');
    if (session.counters.navigations >= this.limit(session.scope.maxNavigations, this.budgets.maxNavigations)) throw new BrowserAgentError('BUDGET_EXCEEDED', 'Browser navigation budget exceeded.');
    const decision = this.policy.authorize(this.snapshot(session), undefined, { type: 'OPEN_TAB', url: normalized });
    if (!decision.allowed) throw new BrowserAgentError(decision.code ?? 'INTENT_NOT_ALLOWED', decision.reason ?? 'Opening this tab is not allowed.');
    if (this.toolPolicy) {
      let allowed = false;
      try { allowed = await this.toolPolicy.authorizeBrowserIntent({ sessionId, ownerAgentId: session.ownerAgentId, intent: { type: 'OPEN_TAB', url: normalized } }); } catch { allowed = false; }
      if (!allowed) throw new BrowserAgentError('INTENT_NOT_ALLOWED', 'The existing ToolPolicy denied opening this browser tab.');
    }
    const tabId = randomId('browser-tab');
    let output: BrowserHostActionOutput | void;
    try { output = this.host.openTab ? await this.host.openTab(tabId, normalized, { sessionId }) : await this.host.execute({ type: 'OPEN_TAB', url: normalized, tabId }, { sessionId, tabId }); } catch (error) { throw new BrowserAgentError('HOST_FAILED', errorMessage(error)); }
    let page: BrowserPageState;
    try { page = output?.page ? sanitizePage(output.page, tabId, 1) : sanitizePage(await this.host.observe(tabId), tabId, 1); } catch (error) { throw new BrowserAgentError('HOST_FAILED', errorMessage(error)); }
    this.assertAllowedOrigin(session, page.url);
    const tab: BrowserTabState = { id: tabId, url: page.url, title: page.title || title.slice(0, 120), pageRevision: page.pageRevision, activity: 'IDLE', page, createdAt: iso(this.now) };
    session.tabs.set(tabId, tab);
    session.activeTabId = tabId;
    session.counters = { ...session.counters, navigations: session.counters.navigations + 1 };
    this.touch(session, 'IDLE');
    return this.publicTab(session, tab);
  }

  async observe(sessionId: string, tabId = this.requireSession(sessionId).activeTabId): Promise<BrowserContext> {
    const session = this.requireSession(sessionId);
    const tab = this.requireTab(session, tabId);
    session.activity = 'OBSERVING';
    this.touch(session, 'OBSERVING');
    let observed: BrowserPageState;
    try { observed = await this.host.observe(tab.id); } catch (error) { session.activity = 'FAILED'; this.touch(session, 'FAILED'); throw new BrowserAgentError('HOST_FAILED', errorMessage(error)); }
    const page = sanitizePage(observed, tab.id, Math.max(tab.pageRevision, observed.pageRevision));
    this.assertAllowedOrigin(session, page.url);
    if (session.execution === 'external' && isPrivate(page.dataClass)) throw new BrowserAgentError('PRIVATE_PAGE_EXTERNAL', 'External AI cannot observe a private authenticated page.');
    this.updateTab(session, tab.id, page, 'IDLE');
    return this.extractor.extractForSession(session.id, page);
  }

  /**
   * Captures the currently bound tab for an explicit local Web Library save.
   * The browser host owns origin/network mechanics; the runtime only exposes
   * a bounded, revision-bound representation and rejects unsupported hosts.
   */
  async capturePage(sessionId: string, request: BrowserCaptureRequest, tabId = this.requireSession(sessionId).activeTabId): Promise<BrowserCapturedPage> {
    const session = this.requireSession(sessionId);
    const tab = this.requireTab(session, tabId);
    if (request?.ownerConfirmed !== true) throw new BrowserAgentError('CONFIRMATION_REQUIRED', 'Explicit owner confirmation is required before saving a browser page.');
    if (request.mode !== 'READER_SNAPSHOT' && request.mode !== 'SAFE_PAGE_ARCHIVE') throw new BrowserAgentError('INVALID_ARGUMENT', 'Unsupported browser capture mode.');
    if (!this.host.capturePage) throw new BrowserAgentError('HOST_UNAVAILABLE', 'The browser host does not expose the explicit capture capability.');
    if (session.paused) throw new BrowserAgentError('PAUSED', 'Browser capture is paused for human takeover.');
    if (session.counters.steps >= this.limit(session.scope.maxSteps, this.budgets.maxSteps)) throw new BrowserAgentError('BUDGET_EXCEEDED', 'Browser capture step budget exceeded.');

    const page = await this.refreshCapturePage(session, tab);
    if (request.expectedPageRevision !== undefined && request.expectedPageRevision !== page.pageRevision) throw new BrowserAgentError('STALE_PAGE', 'The page changed; observe again before saving.');
    if (session.execution === 'external' && isPrivate(page.dataClass)) throw new BrowserAgentError('CAPTURE_NOT_ALLOWED', 'External browser execution cannot save a private page.');
    if (request.signal?.aborted) throw new BrowserAgentError('CANCELLED', 'Browser capture was canceled.');
    session.counters = { ...session.counters, steps: session.counters.steps + 1 };
    session.activity = 'ACTING';
    this.touch(session, 'ACTING');
    let captured: BrowserCapturedPage;
    try {
      captured = await this.host.capturePage(tab.id, request, { sessionId, ownerAgentId: session.ownerAgentId, tabId: tab.id, pageRevision: page.pageRevision, origin: page.origin, dataClass: page.dataClass, signal: request.signal });
    } catch (error) {
      session.counters = { ...session.counters, failedActions: session.counters.failedActions + 1 };
      throw error instanceof BrowserAgentError ? error : new BrowserAgentError('HOST_FAILED', errorMessage(error));
    }
    const normalized = sanitizeCapturedPage(captured, request);
    const finalUrl = normalized.finalUrl ?? normalized.requestedUrl;
    this.assertAllowedOrigin(session, finalUrl);
    if (request.signal?.aborted) throw new BrowserAgentError('CANCELLED', 'Browser capture was canceled.');
    this.touch(session, 'IDLE');
    return normalized;
  }

  async dispatch(sessionId: string, intent: BrowserIntent): Promise<BrowserActionResult> {
    const session = this.requireSession(sessionId);
    if (!intent || !BROWSER_INTENT_TYPES.includes(intent.type)) return this.result('REJECTED', sessionId, intent?.type ?? 'WAIT_FOR_STATE', undefined, 'INVALID_ARGUMENT', 'Unknown browser intent.');
    if (session.paused) return this.result('REJECTED', sessionId, intent.type, session.activeTabId, 'PAUSED', 'Browser agent is paused for human takeover.');
    if (session.counters.steps >= this.limit(session.scope.maxSteps, this.budgets.maxSteps)) return this.result('FAILED', sessionId, intent.type, session.activeTabId, 'BUDGET_EXCEEDED', 'Browser step budget exceeded.');
    const tabId = intent.tabId ?? (intent.type === 'OPEN_TAB' ? undefined : session.activeTabId);
    if (intent.type === 'OPEN_TAB') {
      try { const tab = await this.openTab(sessionId, intent.url ?? '', 'Browser'); return this.result('COMPLETED', sessionId, intent.type, tab.id, undefined, undefined, tab.page?.pageRevision, tab.page); } catch (error) { return this.fromError(sessionId, intent.type, undefined, error); }
    }
    if (!tabId) return this.result('REJECTED', sessionId, intent.type, undefined, 'TAB_NOT_FOUND', 'An active browser tab is required.');
    const tab = this.requireTab(session, tabId);
    let page = tab.page;
    // External execution is never allowed to rely on a stale public snapshot:
    // refresh the host classification before any model-visible action.  This
    // also catches an authenticated redirect before policy evaluation.
    if (session.execution === 'external') {
      try {
        const current = await this.host.observe(tab.id);
        page = sanitizePage(current, tab.id, tab.pageRevision);
        this.updateTab(session, tab.id, page, tab.activity);
      } catch (error) {
        return this.fromError(sessionId, intent.type, tab.id, error);
      }
    }
    if (intent.expectedPageRevision !== undefined && intent.expectedPageRevision !== tab.pageRevision) return this.result('STALE', sessionId, intent.type, tab.id, 'STALE_PAGE', 'The page changed; observe again before acting.', tab.pageRevision, page);
    const target = intent.target ?? intent.element ?? intent.elementRef;
    if (target && (target.pageRevision !== tab.pageRevision || !tab.page?.interactiveElements.some(element => element.id === target.id && element.elementRevision === target.elementRevision))) return this.result('STALE', sessionId, intent.type, tab.id, 'STALE_ELEMENT', 'The semantic element reference is stale; observe again.', tab.pageRevision, page);
    const decision = this.policy.authorize(this.snapshot(session), page, intent);
    if (!decision.allowed) return this.result(decision.requiresConfirmation ? 'NEEDS_CONFIRMATION' : 'REJECTED', sessionId, intent.type, tab.id, decision.code, decision.reason, tab.pageRevision, page);
    if (this.toolPolicy) {
      let allowed = false;
      try { allowed = await this.toolPolicy.authorizeBrowserIntent({ sessionId, ownerAgentId: session.ownerAgentId, intent, pageDataClass: page?.dataClass }); } catch { allowed = false; }
      if (!allowed) return this.result('REJECTED', sessionId, intent.type, tab.id, 'INTENT_NOT_ALLOWED', 'The existing ToolPolicy denied this browser intent.', tab.pageRevision, page);
    }
    if (intent.type === 'DOWNLOAD' && session.counters.downloads >= this.limit(session.scope.maxDownloads, this.budgets.maxDownloads)) return this.result('FAILED', sessionId, intent.type, tab.id, 'DOWNLOAD_LIMIT', 'Download budget exceeded.', tab.pageRevision, page);
    if (intent.type === 'NAVIGATE' && session.counters.navigations >= this.limit(session.scope.maxNavigations, this.budgets.maxNavigations)) return this.result('FAILED', sessionId, intent.type, tab.id, 'BUDGET_EXCEEDED', 'Browser navigation budget exceeded.', tab.pageRevision, page);
    session.counters = { ...session.counters, steps: session.counters.steps + 1 };
    if (intent.type === 'NAVIGATE') session.activity = 'NAVIGATING';
    else session.activity = intent.type === 'WAIT_FOR_STATE' ? 'WAITING' : 'ACTING';
    this.touch(session, session.activity);
    let output: BrowserHostActionOutput;
    try {
      if (intent.type === 'CLOSE_TAB') {
        if (this.host.closeTab) await this.host.closeTab(tab.id, { sessionId });
        session.tabs.delete(tab.id);
        session.activeTabId = session.tabs.keys().next().value;
        this.touch(session, 'IDLE');
        return this.result('COMPLETED', sessionId, intent.type, tab.id, undefined, undefined, undefined);
      }
      if (intent.type === 'SWITCH_TAB') {
        const targetId = intent.tabIdToSwitch ?? intent.tabId;
        if (!targetId || !session.tabs.has(targetId)) return this.result('REJECTED', sessionId, intent.type, tab.id, 'TAB_NOT_FOUND', 'Target tab does not exist.');
        session.activeTabId = targetId;
        this.touch(session, 'IDLE');
        return this.result('COMPLETED', sessionId, intent.type, targetId, undefined, undefined, session.tabs.get(targetId)?.pageRevision);
      }
      output = await this.host.execute(intent, { sessionId, tabId: tab.id });
    } catch (error) {
      session.counters = { ...session.counters, failedActions: session.counters.failedActions + 1 };
      const failure = this.fromError(sessionId, intent.type, tab.id, error);
      session.activity = 'FAILED'; this.touch(session, 'FAILED');
      return failure;
    }
    let nextPage = output.page ? sanitizePage(output.page, tab.id, tab.pageRevision + 1) : undefined;
    const needsObserve = !nextPage && mutatesPage(intent.type);
    if (needsObserve) {
      try { nextPage = sanitizePage(await this.host.observe(tab.id), tab.id, tab.pageRevision + 1); } catch { /* action may have completed while the host is loading */ }
    }
    if (nextPage) {
      try { this.assertAllowedOrigin(session, nextPage.url); } catch (error) { return this.fromError(sessionId, intent.type, tab.id, error); }
      if (session.execution === 'external' && isPrivate(nextPage.dataClass)) return this.result('REJECTED', sessionId, intent.type, tab.id, 'PRIVATE_PAGE_EXTERNAL', 'External AI cannot access the redirected private page.', nextPage.pageRevision);
      this.updateTab(session, tab.id, nextPage, 'IDLE');
    } else this.updateTab(session, tab.id, tab.page, 'IDLE');
    if (intent.type === 'NAVIGATE') session.counters = { ...session.counters, navigations: session.counters.navigations + 1 };
    let download: BrowserDownloadResult | undefined;
    if (output.download) {
      try { download = await this.quarantineDownload(session, output.download); } catch (error) { session.counters = { ...session.counters, failedActions: session.counters.failedActions + 1 }; return this.fromError(sessionId, intent.type, tab.id, error); }
    }
    this.touch(session, 'IDLE');
    return { version: 1, status: 'COMPLETED', intent: intent.type, sessionId, tabId: tab.id, pageRevision: nextPage?.pageRevision ?? tab.pageRevision, ...(output.value !== undefined ? { value: output.value } : {}), ...(nextPage ? { page: nextPage } : {}), ...(output.screenshotRef ? { value: { screenshotRef: output.screenshotRef, ...(output.value !== undefined ? { result: output.value } : {}) } } : {}), ...(download ? { download } : {}) };
  }

  async runTask(input: BrowserTaskRunInput): Promise<BrowserTaskRunResult> {
    const session = this.requireSession(input.sessionId);
    const runId = randomId('browser-run');
    const budget = normalizeBudgets({ ...this.budgets, ...(session.scope as Partial<BrowserRuntimeBudgets>), ...(input.budgets ?? {}) });
    const started = this.now();
    let steps = 0;
    let artifactIds: string[] = [];
    const controller = new AbortController();
    const onAbort = () => controller.abort(input.signal?.reason);
    input.signal?.addEventListener('abort', onAbort, { once: true });
    try {
      while (steps < budget.maxSteps) {
        if (controller.signal.aborted) return { id: runId, sessionId: input.sessionId, state: 'CANCELLED', steps, artifactIds, reason: 'Cancelled by caller.' };
        if (this.now() - started > budget.maxRuntimeMs) return { id: runId, sessionId: input.sessionId, state: 'NEEDS_USER', steps, artifactIds, reason: 'Browser runtime budget expired.' };
        const context = await this.observe(input.sessionId, input.tabId ?? session.activeTabId);
        const plan = await input.planner({ session: this.snapshot(this.requireSession(input.sessionId)), context, step: steps, signal: controller.signal });
        if (plan.done || !plan.intent) return { id: runId, sessionId: input.sessionId, state: 'COMPLETED', steps, artifactIds };
        const result = await this.dispatch(input.sessionId, plan.intent);
        steps += 1;
        if (result.status === 'NEEDS_CONFIRMATION') return { id: runId, sessionId: input.sessionId, state: 'NEEDS_USER', steps, artifactIds, reason: result.message };
        if (result.status !== 'COMPLETED') {
          if (this.requireSession(input.sessionId).counters.failedActions >= budget.maxFailedActions) return { id: runId, sessionId: input.sessionId, state: 'FAILED', steps, artifactIds, reason: result.message ?? result.errorCode };
        }
      }
      return { id: runId, sessionId: input.sessionId, state: 'NEEDS_USER', steps, artifactIds, reason: 'Maximum browser steps reached.' };
    } catch (error) {
      return { id: runId, sessionId: input.sessionId, state: 'FAILED', steps, artifactIds, reason: errorMessage(error) };
    } finally { input.signal?.removeEventListener('abort', onAbort); }
  }

  pause(sessionId: string): BrowserSession { const session = this.requireSession(sessionId); session.paused = true; this.touch(session, 'PAUSED'); return this.snapshot(session); }
  resume(sessionId: string): BrowserSession { const session = this.requireSession(sessionId); session.paused = false; this.touch(session, 'IDLE'); return this.snapshot(session); }
  takeControl(sessionId: string): BrowserSession { return this.pause(sessionId); }
  stop(sessionId: string): Promise<void> { return this.closeSession(sessionId); }

  async recordManualAction(sessionId: string, tabId = this.requireSession(sessionId).activeTabId): Promise<BrowserPageState> {
    const session = this.requireSession(sessionId);
    const tab = this.requireTab(session, tabId);
    let page: BrowserPageState | undefined;
    if (this.host.manualAction) page = (await this.host.manualAction(tab.id, { sessionId })) ?? undefined;
    if (!page) page = await this.host.observe(tab.id);
    const next = sanitizePage(page, tab.id, tab.pageRevision + 1);
    this.updateTab(session, tab.id, next, 'IDLE');
    session.paused = true;
    this.touch(session, 'PAUSED');
    return next;
  }

  async createArtifact(sessionId: string, input: { tabId?: string; extractedData: unknown; citations?: readonly BrowserArtifactCitation[]; fileRefs?: readonly string[]; screenshotRef?: string }): Promise<BrowserArtifact> {
    const session = this.requireSession(sessionId);
    const tab = this.requireTab(session, input.tabId ?? session.activeTabId);
    const page = tab.page ?? await this.host.observe(tab.id);
    const safePage = sanitizePage(page, tab.id, tab.pageRevision);
    if (session.execution === 'external' && isPrivate(safePage.dataClass)) throw new BrowserAgentError('ARTIFACT_PRIVATE_EXTERNAL', 'Private browser data cannot become an external artifact.');
    if (this.egressFirewall) {
      let allowed = false;
      try { allowed = await this.egressFirewall.checkBrowserArtifact({ sessionId, ownerAgentId: session.ownerAgentId, execution: session.execution, dataClass: safePage.dataClass, sourceOrigin: safePage.origin }); } catch { allowed = false; }
      if (!allowed) throw new BrowserAgentError('ARTIFACT_PRIVATE_EXTERNAL', 'The existing AIEgressFirewall denied this browser artifact.');
    }
    const timestamp = iso(this.now);
    const idValue = randomId('browser-artifact');
    const payload = stableJson({ id: idValue, url: safePage.url, revision: safePage.pageRevision, extractedData: input.extractedData, citations: input.citations ?? [], fileRefs: input.fileRefs ?? [] });
    const artifact: BrowserArtifact = {
      version: 1,
      id: idValue,
      sourceUrl: safePage.url,
      sourceOrigin: safePage.origin,
      extractedData: input.extractedData,
      citations: (input.citations ?? []).slice(0, 128),
      timestamp,
      pageRevision: safePage.pageRevision,
      ...(input.screenshotRef ? { screenshotRef: input.screenshotRef } : {}),
      fileRefs: unique(input.fileRefs),
      provenance: { sessionId, tabId: tab.id, ownerAgentId: session.ownerAgentId, execution: session.execution, sourceType: 'browser-page', untrustedSource: true },
      integrity: { algorithm: 'SHA-256', digest: await digest(payload) },
      dataClass: safePage.dataClass,
      trust: 'UNTRUSTED',
    };
    this.artifacts.set(idValue, artifact);
    return artifact;
  }

  getArtifact(idValue: string): BrowserArtifact | undefined { return this.artifacts.get(idValue); }
  listArtifacts(): readonly BrowserArtifact[] { return [...this.artifacts.values()]; }
  executeIntent(sessionId: string, intent: BrowserIntent): Promise<BrowserActionResult> { return this.dispatch(sessionId, intent); }
  getContext(sessionId: string, tabId?: string): Promise<BrowserContext> { return this.observe(sessionId, tabId); }
  startTask(input: BrowserTaskRunInput): Promise<BrowserTaskRunResult> { return this.runTask(input); }
  getPage(sessionId: string, tabId?: string): BrowserPageState | undefined { const session = this.sessions.get(sessionId); const tab = session && this.requireTab(session, tabId ?? session.activeTabId); if (!tab?.page) return undefined; return session?.execution === 'external' && isPrivate(tab.page.dataClass) ? undefined : tab.page; }

  /** Returns only credential availability metadata; no username/password is exposed. */
  async credentialAvailable(sessionId: string, tabId = this.requireSession(sessionId).activeTabId): Promise<BrowserCredentialAvailability | undefined> {
    if (!this.credentialAdapter) throw new BrowserAgentError('CREDENTIAL_ACCESS_DENIED', 'Credential adapter is unavailable.');
    const session = this.requireSession(sessionId); const tab = this.requireTab(session, tabId); const page = await this.refreshCredentialPage(session, tab);
    if (session.execution === 'external') throw new BrowserAgentError('CREDENTIAL_ACCESS_DENIED', 'External browser agents cannot access credentials.');
    return this.credentialAdapter.available(page.origin, page.pageRevision, { sessionId, tabId: tab.id });
  }

  /** Performs host-side autofill after an explicit confirmation and exact page binding. */
  async fillCredential(sessionId: string, intent: Omit<BrowserCredentialFillIntent, 'confirmed'> & { confirmed?: boolean }, tabId = this.requireSession(sessionId).activeTabId): Promise<{ readonly accepted: true; readonly filledFieldIds: readonly string[] } | { readonly accepted: false; readonly reason: string }> {
    if (!this.credentialAdapter) throw new BrowserAgentError('CREDENTIAL_ACCESS_DENIED', 'Credential adapter is unavailable.');
    const session = this.requireSession(sessionId); const tab = this.requireTab(session, tabId); const page = await this.refreshCredentialPage(session, tab);
    if (session.execution === 'external') throw new BrowserAgentError('CREDENTIAL_ACCESS_DENIED', 'External browser agents cannot autofill credentials.');
    if (intent.confirmed !== true || intent.origin !== page.origin || intent.pageRevision !== page.pageRevision) throw new BrowserAgentError('CREDENTIAL_ACCESS_DENIED', 'Credential intent confirmation, origin or page revision is invalid.');
    if (!safeId(intent.credentialHandleId, 256) || !intent.fieldIds.length || intent.fieldIds.length > 16 || !intent.fieldIds.every(field => safeId(field, 256))) throw new BrowserAgentError('INVALID_ARGUMENT', 'Credential field references are invalid.');
    return this.credentialAdapter.fill({ ...intent, confirmed: true }, { sessionId, tabId: tab.id });
  }

  /** Credential operations always rebind to the host's current page. A
   * previously observed page is not sufficient because navigation or a human
   * action can invalidate the credential scope without updating the runtime
   * snapshot first. */
  private async refreshCredentialPage(session: MutableSession, tab: BrowserTabState): Promise<BrowserPageState> {
    let observed: BrowserPageState;
    try { observed = await this.host.observe(tab.id); } catch { throw new BrowserAgentError('HOST_FAILED', 'Browser host could not refresh the credential page.'); }
    if (Number.isSafeInteger(observed.pageRevision) && observed.pageRevision < tab.pageRevision) throw new BrowserAgentError('CREDENTIAL_ACCESS_DENIED', 'Credential page revision regressed.');
    const page = sanitizePage(observed, tab.id, tab.pageRevision);
    this.assertAllowedOrigin(session, page.url);
    this.updateTab(session, tab.id, page, tab.activity);
    return page;
  }

  private async refreshCapturePage(session: MutableSession, tab: BrowserTabState): Promise<BrowserPageState> {
    let observed: BrowserPageState;
    try { observed = await this.host.observe(tab.id); } catch { throw new BrowserAgentError('HOST_FAILED', 'Browser host could not refresh the capture page.'); }
    const page = sanitizePage(observed, tab.id, tab.pageRevision);
    this.assertAllowedOrigin(session, page.url);
    this.updateTab(session, tab.id, page, tab.activity);
    return page;
  }

  private async quarantineDownload(session: MutableSession, download: BrowserDownload): Promise<BrowserDownloadResult> {
    const scope = this.policy.scopeFor(session.scope);
    if (download.size < 0 || download.size > this.limit(scope.maxDownloadBytes, this.budgets.maxDownloadBytes)) throw new BrowserAgentError('DOWNLOAD_LIMIT', 'Downloaded content exceeds the configured limit.');
    if (!safeMime(download.mimeType)) throw new BrowserAgentError('DOWNLOAD_LIMIT', 'Download MIME type is invalid.');
    const sha256 = download.bytes ? await digestBytes(download.bytes) : await digest(`${download.contentId ?? ''}:${download.size}:${download.sourceUrl}`);
    const bytes = session.counters.downloadedBytes + download.size;
    if (bytes > this.limit(scope.maxDownloadBytes, this.budgets.maxDownloadBytes)) throw new BrowserAgentError('DOWNLOAD_LIMIT', 'Download byte budget exceeded.');
    session.counters = { ...session.counters, downloads: session.counters.downloads + 1, downloadedBytes: bytes };
    if (!this.downloadBoundary) throw new BrowserAgentError('HOST_UNAVAILABLE', 'Browser download quarantine boundary is unavailable.');
    const result = await this.downloadBoundary.quarantine({ ...download, ...(download.bytes ? { bytes: download.bytes.slice() } : {}) }, { sessionId: session.id, ownerAgentId: session.ownerAgentId });
    if (!result || result.quarantine !== 'UNTRUSTED' || !safeId(result.objectId, 256) || result.size !== download.size || result.mimeType !== download.mimeType || result.sha256 !== sha256) throw new BrowserAgentError('HOST_FAILED', 'Browser download boundary returned an invalid quarantine result.');
    return { ...result, filename: result.filename?.slice(0, 240), mimeType: result.mimeType, size: result.size, sourceUrl: result.sourceUrl || download.sourceUrl, quarantine: 'UNTRUSTED' };
  }

  private updateTab(session: MutableSession, tabId: string, page: BrowserPageState | undefined, activity: BrowserActivityState): void {
    const current = session.tabs.get(tabId);
    if (!current) return;
    session.tabs.set(tabId, { ...current, ...(page ? { url: page.url, title: page.title, pageRevision: page.pageRevision, page } : {}), activity });
  }
  private publicTab(session: MutableSession, tab: BrowserTabState): BrowserTabState {
    if (session.execution === 'external' && tab.page && isPrivate(tab.page.dataClass)) return { ...tab, url: 'about:private', title: 'Private page', page: undefined };
    return { ...tab, page: tab.page ? { ...tab.page, interactiveElements: tab.page.interactiveElements.map(sanitizeElement) } : undefined };
  }
  private snapshot(session: MutableSession): BrowserSession { return { ...session, scope: { ...session.scope }, tabs: [...session.tabs.values()].map(tab => { const privatePage = session.execution === 'external' && tab.page && isPrivate(tab.page.dataClass); return { ...tab, ...(privatePage ? { url: 'about:private', title: 'Private page', page: undefined } : { page: tab.page ? { ...tab.page, interactiveElements: tab.page.interactiveElements.map(sanitizeElement) } : undefined }) }; }), counters: { ...session.counters } }; }
  private requireSession(idValue: string): MutableSession { const session = this.sessions.get(idValue); if (!session) throw new BrowserAgentError('SESSION_NOT_FOUND', `Unknown browser session ${idValue}.`); return session; }
  private requireTab(session: MutableSession, tabId: string | undefined): BrowserTabState { const tab = tabId ? session.tabs.get(tabId) : undefined; if (!tab) throw new BrowserAgentError('TAB_NOT_FOUND', 'Unknown browser tab.'); return tab; }
  private touch(session: MutableSession, activity: BrowserActivityState): void { session.activity = activity; session.updatedAt = iso(this.now); }
  private limit(value: number | undefined, fallback: number): number { return Number.isSafeInteger(value) && value! >= 0 ? Math.min(value!, fallback) : fallback; }
  private assertAllowedOrigin(session: MutableSession, url: string): void { const origin = safeOrigin(url); if (!origin) throw new BrowserAgentError('INVALID_REDIRECT', 'The host reported a non-HTTP(S) page.'); const allowed = this.policy.scopeFor(session.scope).allowedOrigins; if (allowed?.length && !allowed.some(candidate => originMatches(origin, candidate))) throw new BrowserAgentError('ORIGIN_BLOCKED', `Redirected origin ${origin} is outside the browser scope.`); }
  private result(status: BrowserActionResult['status'], sessionId: string, intent: BrowserIntentType, tabId?: string, errorCode?: BrowserErrorCode, message?: string, pageRevision?: number, page?: BrowserPageState): BrowserActionResult { const session = this.sessions.get(sessionId); const safePage = session?.execution === 'external' && page && isPrivate(page.dataClass) ? undefined : page; return { version: 1, status, intent, sessionId, ...(tabId ? { tabId } : {}), ...(pageRevision !== undefined ? { pageRevision } : {}), ...(safePage ? { page: safePage } : {}), ...(errorCode ? { errorCode } : {}), ...(message ? { message } : {}) }; }
  private fromError(sessionId: string, intent: BrowserIntentType, tabId: string | undefined, error: unknown): BrowserActionResult { const code = error instanceof BrowserAgentError ? error.code : 'HOST_FAILED'; return this.result('FAILED', sessionId, intent, tabId, code, errorMessage(error)); }
}

function normalizeBudgets(input?: Partial<BrowserRuntimeBudgets>): BrowserRuntimeBudgets {
  return {
    maxTabs: boundedInt(input?.maxTabs, 1, 32, BASE_BUDGETS.maxTabs),
    maxSteps: boundedInt(input?.maxSteps, 1, 512, BASE_BUDGETS.maxSteps),
    maxRuntimeMs: boundedInt(input?.maxRuntimeMs, 100, 30 * 60_000, BASE_BUDGETS.maxRuntimeMs),
    maxNavigations: boundedInt(input?.maxNavigations, 1, 512, BASE_BUDGETS.maxNavigations),
    maxFailedActions: boundedInt(input?.maxFailedActions, 0, 128, BASE_BUDGETS.maxFailedActions),
    maxDownloads: boundedInt(input?.maxDownloads, 0, 64, BASE_BUDGETS.maxDownloads),
    maxDownloadBytes: boundedInt(input?.maxDownloadBytes, 0, 2 * 1024 * 1024 * 1024, BASE_BUDGETS.maxDownloadBytes),
  };
}

function sanitizePage(page: BrowserPageState, tabId: string, minimumRevision: number): BrowserPageState {
  if (!page || typeof page !== 'object') throw new BrowserAgentError('HOST_FAILED', 'Host returned an invalid page state.');
  const url = safeHttpUrl(page.url);
  if (!url) throw new BrowserAgentError('INVALID_REDIRECT', 'Host returned an invalid page URL.');
  const origin = safeOrigin(url);
  if (!origin) throw new BrowserAgentError('INVALID_REDIRECT', 'Host returned an invalid page origin.');
  const dataClass = BROWSER_PAGE_DATA_CLASSES.includes(page.dataClass) ? page.dataClass : page.authenticated ? 'PRIVATE' : 'PUBLIC';
  return {
    version: 1,
    tabId,
    url,
    origin,
    title: String(page.title ?? '').slice(0, 512),
    pageRevision: Math.max(1, Number.isSafeInteger(page.pageRevision) ? page.pageRevision : 1, minimumRevision),
    ...(page.authenticated ? { authenticated: true } : {}),
    dataClass,
    visibleText: String(page.visibleText ?? '').slice(0, 128 * 1024),
    interactiveElements: Array.isArray(page.interactiveElements) ? page.interactiveElements.slice(0, 512).map(sanitizeElement).filter(element => element.id.length > 0) : [],
    ...(page.accessibilitySnapshot ? { accessibilitySnapshot: String(page.accessibilitySnapshot).slice(0, 64 * 1024) } : {}),
    ...(page.screenshotRef ? { screenshotRef: String(page.screenshotRef).slice(0, 512) } : {}),
    ...(page.loading !== undefined ? { loading: Boolean(page.loading) } : {}),
    updatedAt: typeof page.updatedAt === 'string' ? page.updatedAt : new Date().toISOString(),
  };
}

function sanitizeCapturedPage(value: BrowserCapturedPage, request: BrowserCaptureRequest): BrowserCapturedPage {
  if (!value || typeof value !== 'object') throw new BrowserAgentError('HOST_FAILED', 'Browser host returned an invalid capture.');
  const requestedUrl = safeHttpUrl(value.requestedUrl);
  if (!requestedUrl) throw new BrowserAgentError('INVALID_REDIRECT', 'Browser capture returned an invalid requested URL.');
  const finalUrl = value.finalUrl === undefined ? undefined : safeHttpUrl(value.finalUrl);
  if (value.finalUrl !== undefined && !finalUrl) throw new BrowserAgentError('INVALID_REDIRECT', 'Browser capture returned an invalid final URL.');
  if (typeof value.html !== 'string' || !value.html) throw new BrowserAgentError('HOST_FAILED', 'Browser capture returned no page representation.');
  const maxHtmlBytes = boundedInt(request.maxHtmlBytes, 1, 8 * 1024 * 1024, 2 * 1024 * 1024);
  if (new TextEncoder().encode(value.html).byteLength > maxHtmlBytes) throw new BrowserAgentError('CAPTURE_LIMIT', 'Browser capture HTML exceeds the configured bound.');
  const maxResources = boundedInt(request.maxResources, 0, 128, 128);
  const maxResourceBytes = boundedInt(request.maxResourceBytes, 1, 8 * 1024 * 1024, 8 * 1024 * 1024);
  const maxTotalResourceBytes = boundedInt(request.maxTotalResourceBytes, 1, 32 * 1024 * 1024, 32 * 1024 * 1024);
  const sourceResources = value.resources ?? [];
  if (!Array.isArray(sourceResources) || sourceResources.length > maxResources) throw new BrowserAgentError('CAPTURE_LIMIT', 'Browser capture resource count exceeds the configured bound.');
  let totalBytes = 0;
  const resources: BrowserCaptureResource[] = sourceResources.map(resource => {
    const originalUrl = safeHttpUrl(resource.originalUrl);
    if (!originalUrl || !(resource.bytes instanceof Uint8Array) || !safeMime(resource.mimeType) || !['IMAGE', 'SAFE_STYLE', 'FONT', 'OTHER'].includes(resource.kind)) throw new BrowserAgentError('HOST_FAILED', 'Browser capture returned an invalid resource.');
    if (resource.bytes.byteLength > maxResourceBytes || totalBytes + resource.bytes.byteLength > maxTotalResourceBytes) throw new BrowserAgentError('CAPTURE_LIMIT', 'Browser capture resource bytes exceed the configured bound.');
    totalBytes += resource.bytes.byteLength;
    return { originalUrl, bytes: resource.bytes.slice(), mimeType: resource.mimeType, kind: resource.kind };
  });
  const redirectCount = value.redirectCount ?? 0;
  const maxRedirects = boundedInt(request.maxRedirects, 0, 20, 5);
  if (!Number.isSafeInteger(redirectCount) || redirectCount < 0 || redirectCount > maxRedirects) throw new BrowserAgentError('CAPTURE_LIMIT', 'Browser capture redirect bound exceeded.');
  const metadata = value.metadata && typeof value.metadata === 'object' ? {
    ...(value.metadata.description ? { description: String(value.metadata.description).slice(0, 2_000) } : {}),
    ...(value.metadata.siteName ? { siteName: String(value.metadata.siteName).slice(0, 256) } : {}),
    ...(value.metadata.author ? { author: String(value.metadata.author).slice(0, 256) } : {}),
    ...(value.metadata.claimedPublishedAt ? { claimedPublishedAt: String(value.metadata.claimedPublishedAt).slice(0, 128) } : {}),
    ...(value.metadata.language ? { language: String(value.metadata.language).slice(0, 32) } : {}),
  } : undefined;
  return { requestedUrl, ...(finalUrl ? { finalUrl } : {}), title: String(value.title ?? '').slice(0, 512), html: value.html, ...(metadata && Object.keys(metadata).length ? { metadata } : {}), resources, redirectCount };
}

function sanitizeElement(element: BrowserInteractiveElement): BrowserInteractiveElement {
  return { id: String(element?.id ?? '').slice(0, 256), ...(element?.role ? { role: String(element.role).slice(0, 80) } : {}), ...(element?.label ? { label: String(element.label).slice(0, 512) } : {}), ...(element?.text ? { text: String(element.text).slice(0, 512) } : {}), pageRevision: Number.isSafeInteger(element?.pageRevision) ? element.pageRevision : 0, elementRevision: Number.isSafeInteger(element?.elementRevision) ? element.elementRevision : 0, ...(element?.disabled !== undefined ? { disabled: Boolean(element.disabled) } : {}), ...(element?.checked !== undefined ? { checked: Boolean(element.checked) } : {}), ...(element?.inputType ? { inputType: element.inputType } : {}) };
}

function mutatesPage(type: BrowserIntentType): boolean { return type === 'NAVIGATE' || type === 'BACK' || type === 'FORWARD' || type === 'RELOAD' || type === 'CLICK' || type === 'TYPE' || type === 'SELECT' || type === 'SCROLL' || type === 'SUBMIT' || type === 'UPLOAD_EXPLICIT_FILE' || type === 'WAIT_FOR_STATE'; }
function denied(code: BrowserErrorCode, reason: string): BrowserPolicyDecision { return { allowed: false, code, reason }; }
function isPrivate(value: BrowserPageDataClass): boolean { return value === 'PRIVATE' || value === 'SECRET'; }
function safeId(value: unknown, max: number): value is string { return typeof value === 'string' && value.length > 0 && value.length <= max && !/[\u0000-\u001f]/.test(value); }
function safeHttpUrl(value: string): string | undefined { try { const url = new URL(value); if (url.protocol !== 'https:' && url.protocol !== 'http:') return undefined; if (url.username || url.password) return undefined; return url.toString(); } catch { return undefined; } }
function safeOrigin(value: string): string | undefined { const url = safeHttpUrl(value); return url ? new URL(url).origin : undefined; }
function originMatches(origin: string, allowed: string): boolean { const normalized = safeOrigin(allowed); return Boolean(normalized && origin === normalized); }
function safeMime(value: string): boolean { return typeof value === 'string' && value.length > 0 && value.length <= 160 && /^[\w.+-]+\/[\w.+-]+$/.test(value); }
function boundedInt(value: number | undefined, min: number, max: number, fallback: number): number { return Number.isSafeInteger(value) ? Math.max(min, Math.min(max, value!)) : fallback; }
function randomId(prefix: string): string { const uuid = globalThis.crypto?.randomUUID?.(); if (!uuid) throw new Error('Secure randomness is unavailable'); return `${prefix}-${uuid}`; }
function iso(now: () => number): string { return new Date(now()).toISOString(); }
function errorMessage(error: unknown): string { return error instanceof Error ? error.message : String(error); }
function unique(values: readonly string[] | undefined, max = 128): string[] { return [...new Set((values ?? []).filter(value => safeId(value, 512)))].slice(0, max); }
function stableJson(value: unknown): string { try { return JSON.stringify(value, (_key, child) => child instanceof Uint8Array ? Array.from(child) : child) ?? 'null'; } catch { return '[unserializable]'; } }
function bytesToString(value: Uint8Array): string { let result = ''; for (const byte of value) result += String.fromCharCode(byte); return result; }
async function digest(value: string): Promise<string> {
  const subtle = globalThis.crypto?.subtle;
  if (subtle) {
    const encoded = new TextEncoder().encode(value);
    const buffer = await subtle.digest('SHA-256', encoded);
    return [...new Uint8Array(buffer)].map(byte => byte.toString(16).padStart(2, '0')).join('');
  }
  // Deterministic fallback for constrained host runtimes.  Native hosts should
  // provide Web Crypto; this fallback is only an integrity marker, not crypto.
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) { hash ^= value.charCodeAt(index); hash = Math.imul(hash, 16777619); }
  return `fallback-${(hash >>> 0).toString(16).padStart(8, '0')}`;
}
async function digestBytes(value: Uint8Array): Promise<string> {
  const subtle = globalThis.crypto?.subtle;
  if (subtle) {
    const input = new Uint8Array(value.length); input.set(value);
    const buffer = await subtle.digest('SHA-256', input.buffer as ArrayBuffer);
    return [...new Uint8Array(buffer)].map(byte => byte.toString(16).padStart(2, '0')).join('');
  }
  return digest(bytesToString(value));
}
